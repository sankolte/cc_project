// tests/verify-phase3.js
// Automated Verification Script for Phase 3 (Live Web Dashboard & Chaos Simulator)

const fs = require('fs');
const path = require('path');

console.log('====================================================');
console.log('🧪 VERIFYING PHASE 3: LIVE DASHBOARD & CHAOS SIMULATOR');
console.log('====================================================\n');

let passedTests = 0;
let totalTests = 0;

function assert(condition, testName) {
  totalTests++;
  if (condition) {
    console.log(`✅ [PASS] ${testName}`);
    passedTests++;
  } else {
    console.error(`❌ [FAIL] ${testName}`);
  }
}

// 1. Static Asset Validation
const publicDir = path.resolve(__dirname, '..', 'monitor-server', 'public');
const htmlFile = path.join(publicDir, 'index.html');
const cssFile = path.join(publicDir, 'styles.css');
const jsFile = path.join(publicDir, 'app.js');
const simFile = path.resolve(__dirname, '..', 'simulator.js');

assert(fs.existsSync(htmlFile), 'Dashboard index.html exists');
assert(fs.existsSync(cssFile), 'Dashboard styles.css exists');
assert(fs.existsSync(jsFile), 'Dashboard app.js exists');
assert(fs.existsSync(simFile), 'Traffic simulator.js exists');

const htmlContent = fs.readFileSync(htmlFile, 'utf8');
assert(htmlContent.includes('chart.umd.min.js'), 'Dashboard includes Chart.js script');
assert(htmlContent.includes('id="heroStatus"'), 'Dashboard includes Hero Status banner');
assert(htmlContent.includes('id="latencyChart"'), 'Dashboard includes Latency Chart canvas');
assert(htmlContent.includes('id="statusChart"'), 'Dashboard includes Status Code Distribution canvas');
assert(htmlContent.includes('id="incidentsTableBody"'), 'Dashboard includes Incidents Table');

// 2. Integration Test: Run Monitor Server + Target App + Simulator
const MONITOR_PORT = 5997;
const TARGET_PORT = 3997;

process.env.USE_MOCK_AWS = 'true';
process.env.MONITOR_PORT = `${MONITOR_PORT}`;
process.env.TARGET_PORT = `${TARGET_PORT}`;
process.env.MONITOR_INGESTION_URL = `http://localhost:${MONITOR_PORT}/api/telemetry`;
process.env.TARGET_HOST = `http://localhost:${TARGET_PORT}`;

const { app: monitorApp, initialize, worker } = require('../monitor-server/server');
const targetApp = require('../target-app/server');
const simulator = require('../simulator');

async function runTests() {
  let monitorServer;
  let targetServer;

  try {
    await initialize();
    monitorServer = await new Promise(r => { const s = monitorApp.listen(MONITOR_PORT, () => r(s)); });
    targetServer = await new Promise(r => { const s = targetApp.listen(TARGET_PORT, () => r(s)); });
    console.log(`📡 Monitor Server on port ${MONITOR_PORT}, Target App on port ${TARGET_PORT}\n`);

    // Test 3: Dashboard HTML serving
    const resHtml = await fetch(`http://localhost:${MONITOR_PORT}/`);
    assert(resHtml.status === 200, 'Monitor server serves Dashboard on GET / (HTTP 200)');
    const bodyHtml = await resHtml.text();
    assert(bodyHtml.includes('CloudPulse Anomaly Engine'), 'Served page contains correct platform branding');

    // Test 4: Simulator Normal Traffic
    await simulator.simulateNormal(2);
    // Allow queue worker to process
    await new Promise(r => setTimeout(r, 800));

    const resStats1 = await fetch(`http://localhost:${MONITOR_PORT}/api/stats`);
    const dataStats1 = await resStats1.json();
    assert(dataStats1.data.totalRequests >= 4, 'Simulator normal requests were captured and aggregated in stats');
    assert(dataStats1.data.status === 'HEALTHY', 'Status remains HEALTHY under normal traffic');

    // Test 5: Simulator High Latency Chaos Injection
    await simulator.simulateSlow(1, 1800);
    await new Promise(r => setTimeout(r, 800));

    const resStats2 = await fetch(`http://localhost:${MONITOR_PORT}/api/stats`);
    const dataStats2 = await resStats2.json();
    assert(dataStats2.data.status === 'CRITICAL', 'Status transitioned to CRITICAL after simulated latency spike');

    const resIncidents = await fetch(`http://localhost:${MONITOR_PORT}/api/incidents`);
    const dataIncidents = await resIncidents.json();
    const slowIncident = dataIncidents.data.find(i => i.type === 'HIGH_LATENCY');
    assert(!!slowIncident, 'HIGH_LATENCY incident successfully generated by simulator');

    // Test 6: Simulator Server 500 Crash Injection
    await simulator.simulateError(1);
    await new Promise(r => setTimeout(r, 800));

    const resIncidents2 = await fetch(`http://localhost:${MONITOR_PORT}/api/incidents`);
    const dataIncidents2 = await resIncidents2.json();
    const errIncident = dataIncidents2.data.find(i => i.type === 'SERVER_ERROR');
    assert(!!errIncident, 'SERVER_ERROR incident successfully generated by simulator');

  } catch (err) {
    console.error('Unhandled test error:', err);
    assert(false, `Unexpected error: ${err.message}`);
  } finally {
    worker.stopWorker();
    if (monitorServer) await new Promise(r => monitorServer.close(r));
    if (targetServer) await new Promise(r => targetServer.close(r));
  }

  console.log('\n----------------------------------------------------');
  console.log(`📊 RESULTS: ${passedTests}/${totalTests} Tests Passed`);
  console.log('----------------------------------------------------');

  if (passedTests === totalTests) {
    console.log('🎉 Phase 3 verification complete and successful!\n');
    process.exit(0);
  } else {
    console.error('⚠️ Phase 3 has failing checks.\n');
    process.exit(1);
  }
}

runTests();
